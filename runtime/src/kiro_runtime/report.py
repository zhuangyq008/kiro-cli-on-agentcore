"""Build the final report (output.md) and result.json from the loop state.

Generated by code, not by the model, so the report always matches the hand-off files.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

from . import service_version

if TYPE_CHECKING:
    from .orchestrator import LoopState, TaskSpec

STATUS_TEXT = {
    "SUCCEEDED": "All acceptance criteria passed independent verification.",
    "INCOMPLETE": "The iteration limit was reached before all acceptance criteria passed.",
    "FAILED": "The task failed before the loop could finish.",
    "TIMED_OUT": "The task exceeded its timeout.",
}
# loop_mode "none" has no verification phase, so success means only that the single run finished.
DIRECT_STATUS_TEXT = {
    **STATUS_TEXT,
    "SUCCEEDED": "The single run finished without errors (loop mode none: not independently verified).",
    "FAILED": "The single run failed.",
}


def build_result(
    spec: TaskSpec,
    status: str,
    state: LoopState,
    error_code: str | None,
    error_message: str | None,
    duration_ms: int,
) -> dict[str, Any]:
    last = next((r for r in reversed(state.rounds) if r.verify is not None), None)
    criteria = []
    if spec.loop_mode == "none":  # no requirements phase: report the caller's criteria as given
        criteria = [
            {"id": f"U-{i}", "text": c, "source": "user", "status": "not_verified", "evidence": None}
            for i, c in enumerate(spec.acceptance_criteria, start=1)
        ]
    if state.requirements is not None:
        results = {r.criterion: r for r in (last.verify.results if last and last.verify else [])}
        for c in state.requirements.acceptance_criteria:
            r = results.get(c.id)
            criteria.append(
                {
                    "id": c.id,
                    "text": c.text,
                    "source": c.source,
                    "status": r.status if r else "not_verified",
                    "evidence": r.evidence if r else None,
                }
            )
    return {
        "task_id": spec.task_id,
        "session_id": spec.session_id,
        "status": status,
        "model": spec.model,
        "effort": spec.effort,
        "effort_applied": state.effort_applied,
        "iterations": state.iteration,
        "max_iterations": spec.max_iterations,
        "duration_ms": duration_ms,
        "credits_used": round(state.credits, 6),
        "criteria": criteria,
        "rounds": [
            {
                "iteration": r.iteration,
                "passed": r.verdict.passed if r.verdict else None,
                "failed": r.verdict.failed if r.verdict else None,
                "next": (r.verdict.next if r.verdict and not r.verdict.passed else None),
            }
            for r in state.rounds
        ],
        "error_code": error_code,
        "error_message": error_message,
        "kiro_config": state.kiro_config,
        "loop_mode": spec.loop_mode,
        "final_answer": state.final_answer,
        "service_version": service_version(),
    }


def _direct_lines(state: LoopState, result: dict[str, Any]) -> list[str]:
    lines = ["## Answer", "", (state.final_answer or "(no final answer)").strip(), ""]
    if result["criteria"]:
        lines += [
            "## Acceptance criteria (not independently verified)",
            "",
            "Loop mode none runs the task once; the agent was asked to check these itself. "
            "Use --loop-mode process for independent verification.",
            "",
            *[f"- {c['id']}: {c['text']}" for c in result["criteria"]],
            "",
        ]
    return lines


def _kiro_config_lines(info: dict[str, Any] | None) -> list[str]:
    if not info:
        return []
    none = "none"
    lines = [
        "## Kiro configuration",
        "",
        f"- Agent: {info.get('agent') or '(loop agents only)'}",
        f"- MCP servers: {', '.join(info.get('mcp_servers') or []) or none}",
        f"- Skills: {', '.join(info.get('skills') or []) or none}",
        f"- Steering files: {len(info.get('steering') or [])}",
        f"- Files: {info.get('files')}, sha256 `{info.get('sha256')}`",
    ]
    if info.get("warnings"):
        lines += ["", "Warnings:", *[f"- {w}" for w in info["warnings"]]]
    return [*lines, ""]


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def build_output_md(spec: TaskSpec, status: str, state: LoopState, result: dict[str, Any]) -> str:
    lines: list[str] = [f"# Task {spec.task_id}", ""]
    status_texts = DIRECT_STATUS_TEXT if spec.loop_mode == "none" else STATUS_TEXT
    passed = sum(1 for c in result["criteria"] if c["status"] == "pass")
    lines += [
        "## Result",
        "",
        f"- Status: **{status}**. {status_texts.get(status, '')}",
        *(
            []
            if spec.loop_mode == "none"
            else [
                f"- Iterations: {state.iteration} / {spec.max_iterations}",
                f"- Acceptance criteria passed: {passed} / {len(result['criteria'])}",
            ]
        ),
        f"- Model: {spec.model or '(not selected)'}, effort: {spec.effort}"
        + ("" if state.effort_applied else " (not supported by this model, ignored)"),
        f"- Credits used: {result['credits_used']:.4f}",
        f"- Loop mode: {spec.loop_mode}",
        f"- Service version: {service_version()}",
    ]
    if result.get("error_code"):
        lines.append(f"- Error: `{result['error_code']}` {result.get('error_message') or ''}")
    lines.append("")
    lines += _kiro_config_lines(state.kiro_config)
    if spec.loop_mode == "none":
        lines += _direct_lines(state, result)

    req = state.requirements
    if req is not None:
        lines += ["## Understanding", "", req.goal, ""]
        if req.scope.in_:
            lines += ["In scope:", *[f"- {s}" for s in req.scope.in_], ""]
        if req.scope.out:
            lines += ["Out of scope:", *[f"- {s}" for s in req.scope.out], ""]

    if result["criteria"] and spec.loop_mode != "none":
        lines += ["## Acceptance criteria", "", "| ID | Criterion | Result |", "|---|---|---|"]
        for c in result["criteria"]:
            lines.append(f"| {c['id']} | {_md_escape(c['text'])} | {c['status']} |")
        lines.append("")
        for c in result["criteria"]:
            if c.get("evidence"):
                lines += [f"**{c['id']} evidence:**", "", "```text", c["evidence"].strip(), "```", ""]

    if req is not None:
        lines += ["## Assumptions", ""]
        if req.assumptions:
            for a in req.assumptions:
                lines.append(
                    f"- **{a.id}** {a.text} (basis: {a.basis}"
                    + (f"; impact: {a.impact})" if a.impact else ")")
                )
        else:
            lines.append("- None")
        lines.append("")
        if state.assumption_history:
            lines += ["### Assumption changes", ""]
            for h in state.assumption_history:
                lines.append(f"- After iteration {h['after_iteration']}: {h.get('revision_note') or ''}")
                for a in h["added"]:
                    lines.append(f"  - added {a['id']}: {a['text']}")
                for a in h["removed"]:
                    lines.append(f"  - removed {a['id']}: {a['text']}")
                for m in h["modified"]:
                    lines.append(f"  - changed {m['id']}: {m['old']['text']} → {m['new']['text']}")
            lines.append("")

    if state.rounds:
        lines += ["## Verification rounds", ""]
        for r in state.rounds:
            if r.verdict is None:
                lines.append(f"- Iteration {r.iteration}: not verified")
            elif r.verdict.passed:
                lines.append(
                    f"- Iteration {r.iteration}: passed ({r.verdict.passed_count}/{r.verdict.total})"
                )
            else:
                lines.append(
                    f"- Iteration {r.iteration}: failed {', '.join(r.verdict.failed)} "
                    f"({r.verdict.passed_count}/{r.verdict.total}), next: {r.verdict.next}"
                )
        lines.append("")
        last_verify = next((r.verify for r in reversed(state.rounds) if r.verify), None)
        if last_verify and last_verify.summary:
            lines += ["### Final verification summary", "", last_verify.summary, ""]
        last_exec = next((r.execution for r in reversed(state.rounds) if r.execution), None)
        if last_exec:
            lines += ["## Execution summary", "", last_exec.summary, ""]
            if last_exec.changes:
                lines += ["Changes:", *[f"- {c}" for c in last_exec.changes], ""]
            if last_exec.deviations:
                lines += ["Deviations from plan:", *[f"- {d}" for d in last_exec.deviations], ""]

    lines += [
        "## Files",
        "",
        "- `loop/`: requirements, plan, per-iteration execution and verification reports",
        "- `artifacts/`: deliverables written by the agent",
        "- `result.json`: machine-readable result",
        "",
    ]
    return "\n".join(lines)
